#!/usr/bin/env bash
# Tests the Android app's SSH core (android/app/src/main/java/dev/termterm/app/ssh)
# on an ordinary JVM, against a throwaway SSH server. No Android SDK needed:
# the core has no Android dependencies.
#
#   npm run test:ssh -w @termterm/mobile      (needs a JDK and Node)
#
# Covers password, public-key and keyboard-interactive logins, host key
# refusal, resize, key generation and import, and that keys made here can be
# read by the desktop app's SSH library and the other way round.
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
src="$here/../android/app/src/main/java/dev/termterm/app/ssh"
work="$(mktemp -d)"
trap 'kill "${server_pid:-}" 2>/dev/null || true; rm -rf "$work"' EXIT

# The same library versions the app is built with (android/app/build.gradle).
fetch() {
  curl -fsSL --retry 3 -o "$work/$2" "https://repo1.maven.org/maven2/$1/$2"
  echo "$3  $work/$2" | sha256sum --check --quiet
}
fetch com/github/mwiede/jsch/2.28.8 jsch-2.28.8.jar 2afca1357d816028f2ac33f22407d2488a68406682973949cebb1b8ea6688a8b
fetch org/bouncycastle/bcprov-jdk18on/1.87 bcprov-jdk18on-1.87.jar 12d2d3dd82a9ec15e92ec7c7943ee64f6097c6dc12c07e984f1693b77565b9aa
cp="$work/jsch-2.28.8.jar:$work/bcprov-jdk18on-1.87.jar"

javac -nowarn -cp "$cp" -d "$work/classes" "$src"/*.java "$here/Smoke.java"

# A passphrase-protected key made by the desktop app's library, to import here.
(cd "$here" && node -e "
const { utils } = require('ssh2')
for (;;) {
  const k = utils.generateKeyPairSync('ed25519', { passphrase: 'secret-pass', cipher: 'aes256-ctr', rounds: 16 })
  if (!(utils.parseKey(k.private, 'secret-pass') instanceof Error)) { require('fs').writeFileSync(process.argv[1], k.private); break }
}" "$work/encrypted.key")

(cd "$here" && node server.cjs "$work/authorized") > "$work/port" &
server_pid=$!
for _ in $(seq 1 50); do [ -s "$work/port" ] && break; sleep 0.1; done

java -cp "$work/classes:$cp" Smoke "$(cat "$work/port")" "$work/authorized" "$work/encrypted.key"

# Keys generated by the Android core must be readable by the desktop app.
(cd "$here" && node -e "
const { utils } = require('ssh2'); const fs = require('fs'); const path = require('path')
for (const type of ['ed25519', 'rsa']) {
  const key = utils.parseKey(fs.readFileSync(path.join(process.argv[1], 'generated-' + type + '.key'), 'utf8'))
  if (key instanceof Error) { console.error('  FAIL desktop cannot read the generated ' + type + ' key: ' + key.message); process.exit(1) }
  console.log('  ok   desktop reads the generated ' + type + ' key (' + key.type + ')')
}" "$work")
